def x_embed(url):
    return html(f'<blockquote class="twitter-tweet" data-lang="ja"><a href="{url}"></a></blockquote>'
                f'<script async src="https://platform.twitter.com/widgets.js" charset="utf-8"></script>')


def gmap(q):
    return html(f'<iframe src="https://maps.google.com/maps?q={quote(q)}&t=&z=15&ie=UTF8&iwloc=&output=embed" '
                f'width="100%" height="350" frameborder="0" scrolling="no" style="border:0;" loading="lazy"></iframe>')


def maplink(name, pref, addr):
    q = quote(f"{pref}{addr} {name.split('(')[0]}")
    return f'<a href="https://www.google.com/maps/search/?api=1&query={q}" target="_blank" rel="noopener">{pref}{addr}</a>'


def shop_rows(shops):
    return [[name, maplink(name, pref, addr), hours] for name, pref, addr, hours in shops]


