def with_images(wp, html):
    note = json.loads(MEDIA_NOTE.read_text(encoding="utf-8")) if MEDIA_NOTE.exists() else {}
    for key, (fn, alt, src) in IMAGES.items():
        if key not in note:
            mid = wp.upload_media(str(IMG_DIR / fn), alt)
            m = wp.get("/media/{}".format(mid))
            note[key] = {"id": mid, "full": m["source_url"], "w": m["media_details"]["width"],
                         "h": m["media_details"]["height"], "sizes": m["media_details"].get("sizes", {})}
            MEDIA_NOTE.write_text(json.dumps(note, ensure_ascii=False, indent=1), encoding="utf-8")

    def rep(mo):
        key, alt = mo.group(1), mo.group(2)
        n = note[key]
        sz = n["sizes"]
        big = sz.get("large") or {"source_url": n["full"], "width": n["w"], "height": n["h"]}
        srcset = []
        for k in ("medium", "large"):
            if k in sz:
                srcset.append("{} {}w".format(sz[k]["source_url"], sz[k]["width"]))
        srcset.append("{} {}w".format(n["full"], n["w"]))
        return ('<img src="{}" alt="{}" width="{}" height="{}" style="max-width:100%;height:auto;" loading="lazy" '
                'srcset="{}" sizes="(max-width: 1024px) 100vw, 1024px">').format(
                    big["source_url"], alt, big["width"], big["height"], ", ".join(srcset))
    return re.sub(r"\{\{IMG:([a-z0-9_]+)\|([^}]*)\}\}", rep, html)


