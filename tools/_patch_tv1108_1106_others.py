def apply(fn, pairs):
    s = open(fn, encoding="utf-8").read()
    for old, new in pairs:
        n = s.count(old)
        assert n == 1, (fn, n, old[:80])
        s = s.replace(old, new)
    open(fn, "w", encoding="utf-8", newline="\n").write(s)
    print("ok", fn)


