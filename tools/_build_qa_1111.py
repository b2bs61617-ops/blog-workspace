def load_env():
    env = {}
    for path, skip in ((os.path.join(REPO, ".env"), ()), (DRIVE_ENV, ("GOOGLE_INDEXING",))):
        if not os.path.exists(path):
            continue
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                k, v = k.strip(), v.strip().strip('"')
                if v and not env.get(k) and not k.startswith(skip or ("\0",)):
                    env[k] = v
    return env


def req(base, auth, path, data=None, headers=None, method="POST"):
    r = urllib.request.Request(base + path, data=data, method=method)
    r.add_header("Authorization", "Basic " + auth)
    for k, v in (headers or {}).items():
        r.add_header(k, v)
    try:
        with urllib.request.urlopen(r, timeout=120) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{e.code} {e.read().decode('utf-8', 'ignore')[:500]}")


