def info(title, rows):
    """施設の基本情報(線の囲みだけ・2列)。"""
    td0 = "border:1px solid #ccc;padding:8px 12px;background:#f0f0f0;width:32%;"
    td1 = "border:1px solid #ccc;padding:8px 12px;"
    trs = "".join('<tr><td style="{}"><strong>{}</strong></td><td style="{}">{}</td></tr>\n'.format(td0, k, td1, v)
                  for k, v in rows)
    return b.html('<div style="border:1px solid #ccc;border-radius:4px;padding:16px 18px;margin:0 0 16px 0;">\n'
                  '<p style="font-weight:bold;font-size:1.05em;margin:0 0 10px 0;">{}</p>\n'
                  '<table style="border-collapse:collapse;width:100%;"><tbody>\n{}</tbody></table>\n</div>'
                  .format(title, trs))


