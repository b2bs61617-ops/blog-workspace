def load_env():
    env = {}
    for line in open(os.path.join(REPO, ".env"), encoding="utf-8"):
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip().strip('"')
    return env


def req(base, auth, path, data=None, headers=None, method="POST"):
    r = urllib.request.Request(base + path, data=data, method=method)
    r.add_header("Authorization", "Basic " + auth)
    for k, v in (headers or {}).items():
        r.add_header(k, v)
    try:
        with urllib.request.urlopen(r, timeout=120) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{e.code} {e.read().decode('utf-8', 'ignore')[:500]}")


def fill_links(html, posted):
    return re.sub(r"\{\{LINK:(\w+)\}\}", lambda m: posted[m.group(1)]["url"] if m.group(1) in posted else "#", html)


def main():
    keys = [k for k in sys.argv[1:] if not k.startswith("--")] or list(ART)
    posted = json.load(open(POSTED, encoding="utf-8")) if os.path.exists(POSTED) else {}
    env = load_env()
