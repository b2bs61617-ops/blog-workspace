        if k in posted:
            pid = posted[k]["id"]
            req(base, auth, f"/wp-json/wp/v2/posts/{pid}",
                json.dumps({"title": a["title"], "content": html, "status": "draft"}).encode("utf-8"),
                {"Content-Type": "application/json"})
