        base = env[f"WP_{s['env']}_URL"].rstrip("/")
        auth = base64.b64encode(f"{env['WP_' + s['env'] + '_USERNAME']}:{env['WP_' + s['env'] + '_APP_PASSWORD']}".encode()).decode()
