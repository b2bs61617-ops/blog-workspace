class Builder:
    def __init__(self, palette):
        self.c = PALETTES[palette]
        self.blocks = []

    def mark(self, text):
        return (f'<strong><span style="font-size:1.1em;background:linear-gradient(transparent 60%,'
                f'{self.c["mk"]} 60%);">{text}</span></strong>')

    def p(self, *lines):
        body = "<br>\n".join(lines)
        self.blocks.append(f"<!-- wp:paragraph -->\n<p>{body}</p>\n<!-- /wp:paragraph -->")

    def h2(self, text):
        self.blocks.append(f'<!-- wp:heading -->\n<h2 class="wp-block-heading">{text}</h2>\n<!-- /wp:heading -->')

    def h3(self, text):
        self.blocks.append(f'<!-- wp:heading {{"level":3}} -->\n<h3 class="wp-block-heading">{text}</h3>\n<!-- /wp:heading -->')

    def html(self, inner):
        self.blocks.append(f"<!-- wp:html -->\n{inner}\n<!-- /wp:html -->")

    def toc(self, *items):
        c = self.c
        lis = "\n".join(f"<li>{i}</li>" for i in items)
        self.html(f'<div style="border:1px solid {c["a"]};border-radius:4px;margin:0 0 16px 0;overflow:hidden;">\n'
                  f'<p style="font-weight:bold;font-size:1.05em;margin:0;padding:10px 18px;background:{c["a"]};color:#fff;">この記事でわかること</p>\n'
                  f'<ul style="margin:0;padding:14px 18px 14px 34px;background:{c["bg"]};">\n{lis}\n</ul>\n</div>')

    def info(self, *pairs):
        c = self.c
        rows = []
        for i, (k, v) in enumerate(pairs):
            margin = "0" if i == 0 else "4px 0 0 0"
            rows.append(f'<p style="margin:{margin};"><strong>{k}:</strong>{v}</p>')
        self.html(f'<div style="border:1px solid {c["l"]};border-left:4px solid {c["a"]};border-radius:4px;'
                  f'padding:10px 16px;margin:0 0 16px 0;background:{c["bg"]};">\n' + "\n".join(rows) + "\n</div>")

    def voice(self, label, *quotes):
        c = self.c
        q = "<br>".join(f"「{x}」" for x in quotes)
        self.html(f'<div style="border:1px solid {c["l"]};border-radius:4px;padding:10px 16px;margin:0 0 16px 0;background:{c["bg"]};">\n'
                  f'<p style="margin:0 0 6px 0;font-weight:bold;font-size:0.9em;color:{c["a"]};">{label}</p>\n'
                  f'<p style="margin:0;font-size:0.95em;">{q}</p>\n</div>')

    def titled_list(self, title, *items, ordered=False):
        c = self.c
        tag = "ol" if ordered else "ul"
        lis = "\n".join(f"<li>{i}</li>" for i in items)
        self.html(f'<div style="border:1px solid {c["l"]};border-radius:4px;margin:0 0 16px 0;overflow:hidden;">\n'
                  f'<p style="font-weight:bold;margin:0;padding:8px 16px;background:{c["a"]};color:#fff;">{title}</p>\n'
                  f'<{tag} style="margin:0;padding:12px 18px 12px 34px;background:{c["bg"]};">\n{lis}\n</{tag}>\n</div>')

    def table(self, rows):
        c = self.c
        trs = []
        for i, row in enumerate(rows):
            style = (f' style="background:{c["a"]};color:#fff;font-weight:bold;border:1px solid {c["l"]};padding:8px;"'
                     if i == 0 else f' style="border:1px solid {c["l"]};padding:8px;"')
            trs.append("<tr>" + "".join(f"<td{style}>{x}</td>" for x in row) + "</tr>")
        self.blocks.append('<!-- wp:table -->\n<figure class="wp-block-table"><table class="has-fixed-layout"><tbody>'
                           + "".join(trs) + "</tbody></table></figure>\n<!-- /wp:table -->")

    def check(self, *items):
        c = self.c
        mark = (f'<span style="display:inline-block;min-width:1.1em;padding:0 3px;border:1px solid {c["a"]};'
                f'border-radius:3px;color:{c["a"]};font-weight:bold;text-align:center;margin-right:6px;font-size:0.85em;">&#10003;</span>')
        rows = "\n".join(f'<p style="margin:0 0 8px 0;">{mark}{i}</p>' for i in items)
        self.html(f'<div style="border:1px solid {c["l"]};border-radius:4px;padding:14px 18px;margin:0 0 16px 0;background:{c["bg"]};">\n{rows}\n</div>')

    def related(self, links):
        c = self.c
        lis = "\n".join(f'<li><a href="{href}">{title}</a></li>' for href, title in links)
        self.html(f'<div style="border:1px solid {c["l"]};border-left:4px solid {c["a"]};border-radius:4px;margin:0 0 16px 0;'
                  f'padding:14px 18px;background:{c["bg"]};">\n<p style="font-weight:bold;font-size:1.05em;margin:0 0 8px 0;">あわせて読みたい</p>\n'
                  f'<ul style="margin:0;padding-left:1.3em;">\n{lis}\n</ul>\n</div>')

    def render(self):
        return "\n\n".join(self.blocks) + "\n"


