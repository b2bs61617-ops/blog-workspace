def photo_url(t):
    import json
    cache = blogkit.ARTICLES / "lupin7_photos.json"
    d = json.loads(cache.read_text(encoding="utf-8")) if cache.exists() else {}
    if t not in d:
        wp = blogkit.WP(SITE)
        mid = wp.upload_media(str(blogkit.ROOT / "images" / (ARTS[t][0] + "_x.jpg")), PHOTOS[t][1])
        m = wp.get("/media/{}".format(mid))
        sizes = m.get("media_details", {}).get("sizes", {})
        d[t] = (sizes.get("medium_large") or sizes.get("large") or sizes.get("full") or {}).get("source_url", m["source_url"])
        cache.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
    return d[t]


