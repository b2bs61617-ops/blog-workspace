def table(head, rows):
    th = "".join(f'<th {TD}>{x}</th>' for x in head)
    trs = []
    for r in rows:
        r = list(r)
        bg = r.pop()["bg"] if isinstance(r[-1], dict) else None
        bold = r[-1] is True
        cells = r[:-1] if bold else r
        td = f'style="padding:8px;border:1px solid #d5d5d5;background:{bg};"' if bg else TD
        trs.append("<tr>" + "".join(f"<td {td}>{'<strong>' + x + '</strong>' if bold else x}</td>" for x in cells) + "</tr>")
    return html(f'<figure class="wp-block-table"><table class="has-fixed-layout"><thead><tr>{th}</tr></thead><tbody>{"".join(trs)}</tbody></table></figure>')


